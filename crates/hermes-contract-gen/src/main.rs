//! Generates `hermes-contract/src/generated.rs` from the vendored OpenRPC document.

use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::Path;
use std::process::ExitCode;

use serde_json::Value;

fn main() -> ExitCode {
    let check = std::env::args().any(|argument| argument == "--check");
    match run(check) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("hermes-contract-gen: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let contract_path = root.join("contract/gateway-contract.openrpc.json");
    let output_path = root.join("crates/hermes-contract/src/generated.rs");

    let text = std::fs::read_to_string(&contract_path)
        .map_err(|error| format!("read {}: {error}", contract_path.display()))?;
    let document: Value = serde_json::from_str(&text)
        .map_err(|error| format!("parse {}: {error}", contract_path.display()))?;

    let methods = names(&document, "methods")?;
    let notifications = names(&document, "x-notifications")?;
    let requests = names(&document, "x-server-requests")?;
    let rendered = render(&methods, &notifications, &requests);

    if check {
        let existing = std::fs::read_to_string(&output_path)
            .map_err(|error| format!("read {}: {error}", output_path.display()))?;
        if existing == rendered {
            println!(
                "contract ok: {} methods, {} notifications, {} server requests",
                methods.len(),
                notifications.len(),
                requests.len()
            );
            return Ok(());
        }
        return Err(format!(
            "{} is stale; run `cargo run -p hermes-contract-gen`",
            output_path.display()
        ));
    }

    std::fs::write(&output_path, rendered)
        .map_err(|error| format!("write {}: {error}", output_path.display()))?;
    println!(
        "wrote {} ({} methods, {} notifications, {} server requests)",
        output_path.display(),
        methods.len(),
        notifications.len(),
        requests.len()
    );
    Ok(())
}

fn names(document: &Value, key: &str) -> Result<Vec<String>, String> {
    let items = document
        .get(key)
        .and_then(Value::as_array)
        .ok_or_else(|| format!("missing array {key}"))?;
    let mut seen = HashSet::new();
    let mut result = Vec::with_capacity(items.len());
    for item in items {
        let name = item
            .get("name")
            .and_then(Value::as_str)
            .ok_or_else(|| format!("{key} entry without a name"))?;
        if seen.insert(name.to_string()) {
            result.push(name.to_string());
        }
    }
    Ok(result)
}

fn render(methods: &[String], notifications: &[String], requests: &[String]) -> String {
    let mut output = String::new();
    output.push_str("// @generated by `cargo run -p hermes-contract-gen`. Do not edit.\n");
    output.push_str("// Source: contract/gateway-contract.openrpc.json\n");
    emit(&mut output, "Method", "method", methods);
    emit(&mut output, "Notification", "notification", notifications);
    emit(&mut output, "ServerRequest", "server request", requests);
    let _ = writeln!(output, "pub const METHOD_COUNT: usize = {};", methods.len());
    let _ = writeln!(
        output,
        "pub const NOTIFICATION_COUNT: usize = {};",
        notifications.len()
    );
    let _ = writeln!(
        output,
        "pub const SERVER_REQUEST_COUNT: usize = {};",
        requests.len()
    );
    output
}

fn emit(output: &mut String, type_name: &str, label: &str, names: &[String]) {
    let variants = variants(names);
    let _ = writeln!(
        output,
        "/// A {label} the gateway accepts.\n#[rustfmt::skip]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum {type_name} {{"
    );
    for variant in &variants {
        let _ = writeln!(output, "    {variant},");
    }
    let _ = writeln!(output, "}}\n#[rustfmt::skip]\nimpl {type_name} {{");
    let all = variants
        .iter()
        .map(|variant| format!("{type_name}::{variant}"))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        output,
        "    pub const ALL: &'static [{type_name}] = &[{all}];"
    );
    let _ = writeln!(
        output,
        "    pub const fn as_str(self) -> &'static str {{\n        match self {{"
    );
    for (name, variant) in names.iter().zip(&variants) {
        let _ = writeln!(output, "            {type_name}::{variant} => {name:?},");
    }
    let _ = writeln!(output, "        }}\n    }}");
    let _ = writeln!(
        output,
        "    pub fn parse(value: &str) -> Option<Self> {{\n        match value {{"
    );
    for (name, variant) in names.iter().zip(&variants) {
        let _ = writeln!(
            output,
            "            {name:?} => Some({type_name}::{variant}),"
        );
    }
    let _ = writeln!(output, "            _ => None,\n        }}\n    }}\n}}");
}

fn variants(names: &[String]) -> Vec<String> {
    let mut used = HashSet::new();
    names
        .iter()
        .map(|name| {
            let base = pascal(name);
            let mut candidate = base.clone();
            let mut suffix = 2;
            while !used.insert(candidate.clone()) {
                candidate = format!("{base}_{suffix}");
                suffix += 1;
            }
            candidate
        })
        .collect()
}

fn pascal(value: &str) -> String {
    let mut output = String::new();
    let mut uppercase = true;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            if uppercase {
                output.push(character.to_ascii_uppercase());
                uppercase = false;
            } else {
                output.push(character);
            }
        } else {
            uppercase = true;
        }
    }
    if output.is_empty() {
        output.push_str("Empty");
    }
    if output.as_bytes()[0].is_ascii_digit() {
        output.insert(0, 'N');
    }
    output
}
